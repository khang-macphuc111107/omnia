//! Unified `Quote + BTW` (`R11`) interaction model and bidirectional `Gemini <-> Notebook` Cross-Bridge.
//!
//! Invariants enforced:
//! - Strict 2-action selection model (`SelectionAction::Quote | SelectionAction::Btw`).
//! - `Quote` produces a structured composer quote card ready for Atelier Studio v3.
//! - `BTW` creates isolated zero-pollution side-threads stored strictly in `notebook_btw_threads`
//!   (never mutating main `notebook_turns`), with explicit `promote_btw_to_source`.
//! - Bidirectional `BridgeDirection::GeminiToNotebook | NotebookToGemini` transfers with secret redaction.

use std::sync::Arc;

use omnia_core::{now_epoch_ms, SecretRedactor};
use serde::{Deserialize, Serialize};
use serde_json::json;
use uuid::Uuid;

use crate::error::NotebookError;
use crate::ingestion::chunk_text_semantically;
use crate::policy::MAX_CHUNK_BYTES;
use crate::source_library::{
    SourceKind, SourceLibrary, SourceRecord, SourceRegistrationInput, SourceRegistrationOutcome,
};
use crate::store::{NotebookStore, StoredBridgeRow, StoredBtwRow};

/// Strict 2-action text selection palette (`R11` — matching `gemini.google.com`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SelectionAction {
    Quote,
    Btw,
}

/// Workspace surface hosting a turn or selection.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum InteractionSurface {
    Gemini,
    Notebook,
}

impl InteractionSurface {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Gemini => "gemini",
            Self::Notebook => "notebook",
        }
    }
}

/// Structured reference to a selected text passage (`QuoteRef` public Wave 3 contract).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct QuoteRef {
    pub quote_id: String,
    pub notebook_id: String,
    pub surface: InteractionSurface,
    pub anchor_turn_id: String,
    pub source_id: Option<String>,
    pub excerpt: String,
    pub char_start: usize,
    pub char_end: usize,
    pub created_at_ms: i64,
}

/// Structured composer quote card generated by `SelectionAction::Quote`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ComposerQuoteCard {
    pub card_id: String,
    pub action: SelectionAction,
    pub quote: QuoteRef,
    pub badge_label: String,
    pub markdown_blockquote: String,
    pub composer_chip_label: String,
}

/// One message inside an isolated zero-pollution BTW side-thread.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BtwMessage {
    pub message_id: String,
    pub role: String,
    pub content: String,
    pub created_at_ms: i64,
}

/// Lifecycle state of an isolated BTW side-thread.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BtwThreadStatus {
    Open,
    Promoted,
    Closed,
}

impl BtwThreadStatus {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Open => "open",
            Self::Promoted => "promoted",
            Self::Closed => "closed",
        }
    }

    #[must_use]
    pub fn from_str_lossy(raw: &str) -> Self {
        match raw.trim().to_ascii_lowercase().as_str() {
            "promoted" => Self::Promoted,
            "closed" => Self::Closed,
            _ => Self::Open,
        }
    }
}

/// Isolated zero-pollution BTW side-thread (`BtwThread` public Wave 3 contract).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BtwThread {
    pub btw_id: String,
    pub notebook_id: String,
    pub anchor_turn_id: String,
    pub anchor_quote: QuoteRef,
    pub status: BtwThreadStatus,
    pub promoted_source_id: Option<String>,
    pub messages: Vec<BtwMessage>,
    pub created_at_ms: i64,
    pub updated_at_ms: i64,
}

/// Result of promoting an isolated BTW side-thread into a first-class Notebook source.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PromoteBtwOutcome {
    pub thread: BtwThread,
    pub source: SourceRecord,
    pub deduplicated: bool,
}

/// Bidirectional Cross-Bridge direction between Gemini and Notebook surfaces.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BridgeDirection {
    GeminiToNotebook,
    NotebookToGemini,
}

impl BridgeDirection {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::GeminiToNotebook => "gemini_to_notebook",
            Self::NotebookToGemini => "notebook_to_gemini",
        }
    }
}

/// Request payload for `POST /api/bridge`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BridgeTransferRequest {
    pub notebook_id: String,
    pub direction: BridgeDirection,
    pub title: String,
    pub content: String,
    #[serde(default)]
    pub source_ids: Vec<String>,
    #[serde(default)]
    pub remote_turn_id: Option<String>,
}

/// Receipt emitted after executing a bidirectional Cross-Bridge transfer.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BridgeTransferReceipt {
    pub event_id: String,
    pub notebook_id: String,
    pub direction: BridgeDirection,
    /// Populated when `direction == BridgeDirection::GeminiToNotebook`.
    pub created_source: Option<SourceRecord>,
    /// Populated when `direction == BridgeDirection::NotebookToGemini`.
    pub gemini_handoff_prompt: Option<String>,
    pub cited_source_ids: Vec<String>,
    pub created_at_ms: i64,
}

/// Request payload to create a structured [`QuoteRef`] + [`ComposerQuoteCard`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CreateQuoteCardRequest {
    pub notebook_id: String,
    pub surface: InteractionSurface,
    pub anchor_turn_id: String,
    #[serde(default)]
    pub source_id: Option<String>,
    pub excerpt: String,
    pub char_start: usize,
    pub char_end: usize,
}

/// Service owning `Quote + BTW` (`R11`) and `Gemini <-> Notebook` Cross-Bridge persistence.
#[derive(Debug, Clone)]
pub struct InteractionService {
    store: Arc<NotebookStore>,
    library: SourceLibrary,
}

impl InteractionService {
    #[must_use]
    pub fn new(store: Arc<NotebookStore>, library: SourceLibrary) -> Self {
        Self { store, library }
    }

    /// Build a structured [`QuoteRef`] + [`ComposerQuoteCard`] for `SelectionAction::Quote`.
    pub fn create_quote_card(
        &self,
        req: CreateQuoteCardRequest,
    ) -> Result<ComposerQuoteCard, NotebookError> {
        let _ = self.library.require_notebook(&req.notebook_id)?;
        let clean_excerpt = SecretRedactor::redact(req.excerpt.trim());
        if clean_excerpt.is_empty() {
            return Err(NotebookError::InvalidInput(
                "quote excerpt cannot be empty".to_string(),
            ));
        }
        if req.char_end < req.char_start {
            return Err(NotebookError::InvalidInput(format!(
                "invalid quote span [{}, {})",
                req.char_start, req.char_end
            )));
        }
        let quote = QuoteRef {
            quote_id: format!("qt_{}", Uuid::new_v4().simple()),
            notebook_id: req.notebook_id,
            surface: req.surface,
            anchor_turn_id: req.anchor_turn_id.trim().to_string(),
            source_id: req.source_id,
            excerpt: clean_excerpt,
            char_start: req.char_start,
            char_end: req.char_end,
            created_at_ms: now_epoch_ms(),
        };
        Ok(build_composer_quote_card(quote))
    }

    /// Start an isolated zero-pollution BTW side-thread anchored to `quote` with an initial question.
    /// Strictly persists ONLY in `notebook_btw_threads` (zero writes to `notebook_turns`).
    pub fn create_btw_thread(
        &self,
        quote: QuoteRef,
        initial_question: &str,
    ) -> Result<BtwThread, NotebookError> {
        let _ = self.library.require_notebook(&quote.notebook_id)?;
        let clean_q = SecretRedactor::redact(initial_question.trim());
        if clean_q.is_empty() {
            return Err(NotebookError::InvalidInput(
                "BTW initial question cannot be empty".to_string(),
            ));
        }
        let now = now_epoch_ms();
        let btw_id = format!("btw_{}", Uuid::new_v4().simple());
        let first_msg = BtwMessage {
            message_id: format!("btwmsg_{}", Uuid::new_v4().simple()),
            role: "user".to_string(),
            content: clean_q,
            created_at_ms: now,
        };
        let thread = BtwThread {
            btw_id: btw_id.clone(),
            notebook_id: quote.notebook_id.clone(),
            anchor_turn_id: quote.anchor_turn_id.clone(),
            anchor_quote: quote,
            status: BtwThreadStatus::Open,
            promoted_source_id: None,
            messages: vec![first_msg],
            created_at_ms: now,
            updated_at_ms: now,
        };
        self.persist_btw(&thread)?;
        Ok(thread)
    }

    /// Append a user or assistant message to an isolated BTW side-thread without polluting main chat.
    pub fn append_btw_message(
        &self,
        btw_id: &str,
        role: &str,
        content: &str,
    ) -> Result<BtwThread, NotebookError> {
        let mut thread = self.get_btw_thread(btw_id)?;
        let clean = SecretRedactor::redact(content.trim());
        if clean.is_empty() {
            return Err(NotebookError::InvalidInput(
                "BTW message content cannot be empty".to_string(),
            ));
        }
        let normalized_role = match role.trim().to_ascii_lowercase().as_str() {
            "user" => "user",
            "assistant" => "assistant",
            "system" => "system",
            other => {
                return Err(NotebookError::InvalidInput(format!(
                    "unsupported BTW message role '{other}'"
                )));
            }
        };
        let now = now_epoch_ms();
        thread.messages.push(BtwMessage {
            message_id: format!("btwmsg_{}", Uuid::new_v4().simple()),
            role: normalized_role.to_string(),
            content: clean,
            created_at_ms: now,
        });
        thread.updated_at_ms = now;
        self.persist_btw(&thread)?;
        Ok(thread)
    }

    /// Fetch a BTW side-thread by ID.
    pub fn get_btw_thread(&self, btw_id: &str) -> Result<BtwThread, NotebookError> {
        let row = self
            .store
            .get_btw_thread(btw_id)?
            .ok_or_else(|| NotebookError::NotFound {
                entity: "btw_thread",
                id: btw_id.to_string(),
            })?;
        btw_from_row(row)
    }

    /// List all BTW side-threads belonging to a notebook.
    pub fn list_btw_threads(&self, notebook_id: &str) -> Result<Vec<BtwThread>, NotebookError> {
        let _ = self.library.require_notebook(notebook_id)?;
        self.store
            .list_btw_threads(notebook_id)?
            .into_iter()
            .map(btw_from_row)
            .collect()
    }

    /// Delete one isolated BTW side-thread by `btw_id` (`DELETE /api/btw/:id`).
    pub fn delete_btw_thread(&self, btw_id: &str) -> Result<bool, NotebookError> {
        let trimmed = btw_id.trim();
        if trimmed.is_empty() {
            return Err(NotebookError::InvalidInput(
                "btw_id cannot be empty".to_string(),
            ));
        }
        self.store.delete_btw_thread(trimmed)
    }

    /// Promote an isolated BTW side-thread into a durable, indexed, SHA-256-deduped Notebook source
    /// (`POST /api/btw/:btwId/promote`), updating `thread.status = Promoted` and `promoted_source_id`.
    pub fn promote_btw_to_source(
        &self,
        btw_id: &str,
        title_override: Option<&str>,
    ) -> Result<PromoteBtwOutcome, NotebookError> {
        let mut thread = self.get_btw_thread(btw_id)?;
        let title = title_override
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .map(SecretRedactor::redact)
            .unwrap_or_else(|| format!("BTW Insight ({})", thread.btw_id));

        let mut md = format!(
            "# {title}\n\n> Anchored excerpt (`{}`):\n> {}\n\n## Side-Thread Transcript\n",
            thread.anchor_turn_id,
            thread.anchor_quote.excerpt.replace('\n', "\n> ")
        );
        for msg in &thread.messages {
            md.push_str(&format!("\n### {}\n\n{}\n", msg.role, msg.content));
        }
        let chunks = chunk_text_semantically(&md, MAX_CHUNK_BYTES);
        let reg: SourceRegistrationOutcome = self.library.register_source(SourceRegistrationInput {
            notebook_id: thread.notebook_id.clone(),
            remote_id: Some(format!("btw:{}", thread.btw_id)),
            title: title.clone(),
            filename: format!("{}.md", thread.btw_id),
            mime_type: Some("text/markdown".to_string()),
            source_kind_override: Some(SourceKind::PromotedBtw),
            raw_bytes: md.into_bytes(),
            chunks,
            ingestion_stage: "promoted_btw_source".to_string(),
            provenance: "EXTRACTED".to_string(),
            metadata: json!({
                "btw_id": thread.btw_id,
                "anchor_turn_id": thread.anchor_turn_id,
                "anchor_quote_id": thread.anchor_quote.quote_id,
                "message_count": thread.messages.len(),
            }),
        })?;

        thread.status = BtwThreadStatus::Promoted;
        thread.promoted_source_id = Some(reg.source.source_id.clone());
        thread.updated_at_ms = now_epoch_ms();
        self.persist_btw(&thread)?;

        Ok(PromoteBtwOutcome {
            thread,
            source: reg.source,
            deduplicated: reg.deduplicated,
        })
    }

    /// Execute a bidirectional `Gemini <-> Notebook` Cross-Bridge transfer (`POST /api/bridge`).
    pub fn bridge_transfer(
        &self,
        req: BridgeTransferRequest,
    ) -> Result<BridgeTransferReceipt, NotebookError> {
        let _ = self.library.require_notebook(&req.notebook_id)?;
        let clean_title = SecretRedactor::redact(req.title.trim());
        let clean_content = SecretRedactor::redact(req.content.trim());
        let now = now_epoch_ms();
        let event_id = format!("brg_{}", Uuid::new_v4().simple());

        match req.direction {
            BridgeDirection::GeminiToNotebook => {
                if clean_content.is_empty() {
                    return Err(NotebookError::InvalidInput(
                        "Gemini-to-Notebook bridge transfer requires non-empty content".to_string(),
                    ));
                }
                let final_title = if clean_title.is_empty() {
                    format!("Gemini Bridge Note ({event_id})")
                } else {
                    clean_title
                };
                let markdown = format!("# {final_title}\n\n{clean_content}");
                let chunks = chunk_text_semantically(&markdown, MAX_CHUNK_BYTES);
                let reg = self.library.register_source(SourceRegistrationInput {
                    notebook_id: req.notebook_id.clone(),
                    remote_id: req.remote_turn_id.clone(),
                    title: final_title,
                    filename: format!("{event_id}.md"),
                    mime_type: Some("text/markdown".to_string()),
                    source_kind_override: Some(SourceKind::Document),
                    raw_bytes: markdown.into_bytes(),
                    chunks,
                    ingestion_stage: "bridge_gemini_to_notebook".to_string(),
                    provenance: "EXTRACTED".to_string(),
                    metadata: json!({
                        "bridge_event_id": event_id,
                        "bridge_direction": BridgeDirection::GeminiToNotebook.as_str(),
                        "remote_turn_id": req.remote_turn_id,
                    }),
                })?;

                self.store.insert_bridge_event(&StoredBridgeRow {
                    event_id: event_id.clone(),
                    notebook_id: req.notebook_id.clone(),
                    direction: BridgeDirection::GeminiToNotebook.as_str().to_string(),
                    payload_json: json!({
                        "title": reg.source.title,
                        "deduplicated": reg.deduplicated,
                        "remote_turn_id": req.remote_turn_id,
                    }),
                    target_source_id: Some(reg.source.source_id.clone()),
                    created_at_ms: now,
                })?;

                Ok(BridgeTransferReceipt {
                    event_id,
                    notebook_id: req.notebook_id,
                    direction: BridgeDirection::GeminiToNotebook,
                    cited_source_ids: vec![reg.source.source_id.clone()],
                    created_source: Some(reg.source),
                    gemini_handoff_prompt: None,
                    created_at_ms: now,
                })
            }
            BridgeDirection::NotebookToGemini => {
                let mut cited_ids = Vec::new();
                let mut sections = Vec::new();
                for sid in &req.source_ids {
                    let resolved = self.library.resolve_citation_ref(&req.notebook_id, sid)?;
                    let chunks = self.store.list_chunks_for_source(&resolved.source_id)?;
                    cited_ids.push(resolved.source_id.clone());
                    for chunk in chunks.iter().take(4) {
                        sections.push(format!(
                            "### [{}:{}] {}\n{}",
                            resolved.source_id, chunk.chunk_idx, resolved.title, chunk.body
                        ));
                    }
                }
                if sections.is_empty() && clean_content.is_empty() {
                    return Err(NotebookError::InvalidInput(
                        "Notebook-to-Gemini bridge requires either source_ids or content"
                            .to_string(),
                    ));
                }
                let heading = if clean_title.is_empty() {
                    "Notebook Grounded Context Handoff".to_string()
                } else {
                    clean_title
                };
                let mut handoff = format!("## {heading}\n");
                if !clean_content.is_empty() {
                    handoff.push_str(&format!("\n{clean_content}\n"));
                }
                if !sections.is_empty() {
                    handoff.push_str("\n### Grounded Sources\n\n");
                    handoff.push_str(&sections.join("\n\n"));
                }
                let handoff = SecretRedactor::redact(&handoff);

                self.store.insert_bridge_event(&StoredBridgeRow {
                    event_id: event_id.clone(),
                    notebook_id: req.notebook_id.clone(),
                    direction: BridgeDirection::NotebookToGemini.as_str().to_string(),
                    payload_json: json!({
                        "title": heading,
                        "cited_source_ids": cited_ids,
                        "handoff_chars": handoff.chars().count(),
                    }),
                    target_source_id: None,
                    created_at_ms: now,
                })?;

                Ok(BridgeTransferReceipt {
                    event_id,
                    notebook_id: req.notebook_id,
                    direction: BridgeDirection::NotebookToGemini,
                    created_source: None,
                    gemini_handoff_prompt: Some(handoff),
                    cited_source_ids: cited_ids,
                    created_at_ms: now,
                })
            }
        }
    }

    /// List Cross-Bridge audit rows for a notebook.
    pub fn list_bridge_events(
        &self,
        notebook_id: &str,
    ) -> Result<Vec<StoredBridgeRow>, NotebookError> {
        let _ = self.library.require_notebook(notebook_id)?;
        self.store.list_bridge_events(notebook_id)
    }

    fn persist_btw(&self, thread: &BtwThread) -> Result<(), NotebookError> {
        let row = StoredBtwRow {
            btw_id: thread.btw_id.clone(),
            notebook_id: thread.notebook_id.clone(),
            anchor_turn_id: thread.anchor_turn_id.clone(),
            anchor_quote_json: serde_json::to_value(&thread.anchor_quote)?,
            status: thread.status.as_str().to_string(),
            promoted_source_id: thread.promoted_source_id.clone(),
            messages_json: serde_json::to_value(&thread.messages)?,
            created_at_ms: thread.created_at_ms,
            updated_at_ms: thread.updated_at_ms,
        };
        self.store.upsert_btw_thread(&row)
    }
}

/// 1-Click Contextual Ask preset matching Atelier Research Studio v3.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ContextualAskPreset {
    Explain,
    Verify,
    Summarize,
    Code,
}

impl ContextualAskPreset {
    #[must_use]
    pub fn parse_lossy(raw: &str) -> Option<Self> {
        match raw.trim().to_ascii_lowercase().as_str() {
            "explain" => Some(Self::Explain),
            "verify" | "factcheck" | "fact_check" => Some(Self::Verify),
            "summarize" | "summary" => Some(Self::Summarize),
            "code" | "implement" => Some(Self::Code),
            _ => None,
        }
    }

    #[must_use]
    pub const fn instruction(self) -> &'static str {
        match self {
            Self::Explain => "Explain the quoted passage clearly from first principles with concrete examples.",
            Self::Verify => "Independently verify every factual and technical claim in the quoted passage, citing exact evidence or flagging gaps.",
            Self::Summarize => "Summarize the quoted passage into concise, high-density structured bullets.",
            Self::Code => "Translate the quoted specification or concept into clean, production-grade runnable code with edge-case handling.",
        }
    }
}

/// Formats zero, one, or multiple [`QuoteRef`] passages plus an optional [`ContextualAskPreset`]
/// into a unified, secret-redacted prompt ready for Atelier Q&A or BTW threads (`R11`).
#[must_use]
pub fn format_multi_quote_prompt(
    quotes: &[QuoteRef],
    preset: Option<ContextualAskPreset>,
    question: &str,
) -> String {
    let mut parts = Vec::new();
    for (idx, q) in quotes.iter().enumerate() {
        let excerpt = SecretRedactor::redact(q.excerpt.trim());
        if excerpt.is_empty() {
            continue;
        }
        let header = match &q.source_id {
            Some(sid) => format!("Quote {} ({} · {sid}):", idx + 1, q.surface.as_str()),
            None => format!("Quote {} ({}):", idx + 1, q.surface.as_str()),
        };
        let bq = excerpt
            .lines()
            .map(|l| format!("> {l}"))
            .collect::<Vec<_>>()
            .join("\n");
        parts.push(format!("{header}\n{bq}"));
    }
    if let Some(p) = preset {
        parts.push(format!("Preset ({:?}): {}", p, p.instruction()));
    }
    let clean_q = SecretRedactor::redact(question.trim());
    if !clean_q.is_empty() {
        parts.push(clean_q);
    }
    parts.join("\n\n")
}

/// Build a structured [`ComposerQuoteCard`] directly from a [`QuoteRef`].
#[must_use]
pub fn build_composer_quote_card(quote: QuoteRef) -> ComposerQuoteCard {
    let chip_preview: String = quote.excerpt.chars().take(48).collect();
    let suffix = if quote.excerpt.chars().count() > 48 {
        "..."
    } else {
        ""
    };
    let badge_label = match (&quote.source_id, quote.surface) {
        (Some(sid), _) => format!("Quote · {sid}"),
        (None, InteractionSurface::Gemini) => "Quote · Gemini".to_string(),
        (None, InteractionSurface::Notebook) => "Quote · Notebook".to_string(),
    };
    let markdown_blockquote = quote
        .excerpt
        .lines()
        .map(|l| format!("> {l}"))
        .collect::<Vec<_>>()
        .join("\n");
    ComposerQuoteCard {
        card_id: format!("qcard_{}", Uuid::new_v4().simple()),
        action: SelectionAction::Quote,
        quote,
        badge_label,
        markdown_blockquote,
        composer_chip_label: format!("{chip_preview}{suffix}"),
    }
}

fn btw_from_row(row: StoredBtwRow) -> Result<BtwThread, NotebookError> {
    let anchor_quote: QuoteRef = serde_json::from_value(row.anchor_quote_json)?;
    let messages: Vec<BtwMessage> = serde_json::from_value(row.messages_json)?;
    Ok(BtwThread {
        btw_id: row.btw_id,
        notebook_id: row.notebook_id,
        anchor_turn_id: row.anchor_turn_id,
        anchor_quote,
        status: BtwThreadStatus::from_str_lossy(&row.status),
        promoted_source_id: row.promoted_source_id,
        messages,
        created_at_ms: row.created_at_ms,
        updated_at_ms: row.updated_at_ms,
    })
}
